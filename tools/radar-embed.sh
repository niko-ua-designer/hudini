#!/bin/sh
# Regenerates server/radar-embed.js: every web/shared/radar/*.webp is compiled into Hudini Host,
# so the OBS widget gets the radar backgrounds even before the site carries them or without internet.
cd "$(dirname "$0")/.."
out=server/radar-embed.js
{
  echo "// Generated by tools/radar-embed.sh: do not edit. Radar backgrounds compiled into the Host binary."
  for f in web/shared/radar/*.webp; do
    n=$(basename "$f" .webp); v=$(echo "$n" | tr -c 'a-zA-Z0-9\n' '_')
    echo "import r_$v from '../$f' with { type: 'file' };"
  done
  echo "export default {"
  for f in web/shared/radar/*.webp; do
    n=$(basename "$f" .webp); v=$(echo "$n" | tr -c 'a-zA-Z0-9\n' '_')
    echo "  '$n.webp': r_$v,"
  done
  echo "};"
} > "$out"
