// ---------- runtime ----------
// The UI is written in Russian. This script translates it in place, using the dictionaries above:
// whole phrases first, then known fragments inside dynamic text (numbers, names, file names stay as they are).
// Mark user content (stage preview, chat, names) with data-i18n-skip so it is never translated.
(function(){
  'use strict';
  const LANGS = [['ru','Русский'], ['en','English'], ['uk','Українська'], ['de','Deutsch']];
  const KEY = 'hudini.lang';
  const CYR = /[А-Яа-яЁёІіЇїЄєҐґ]/;
  const ATTRS = ['title', 'placeholder', 'aria-label', 'alt', 'label'];
  const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT']);
  const NO_TEXT = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA']);   // textarea text is user input; its placeholder is still translated

  let saved = null;
  try{ saved = localStorage.getItem(KEY); }catch{}
  if(!LANGS.some(l => l[0] === saved)) saved = null;
  const lang = saved || 'ru';
  const dict = lang !== 'ru' ? HUDINI_DICT[lang] || null : null;
  document.documentElement.lang = lang;

  function setLang(l){
    try{ localStorage.setItem(KEY, l); }catch{}
    if(l !== lang) location.reload();
  }

  // ---- translation ----
  let translate = s => s;
  if(dict){
    const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const isWord = /[\p{L}\p{N}]/u;
    // 1–2 letter keys (units like «с») are too ambiguous inside sentences: whole-text match only
    const keys = Object.keys(dict).filter(k => CYR.test(k) && k.length > 2).sort((a, b) => b.length - a.length);
    // Longest first; word boundaries only where the key itself starts/ends with a letter
    const re = new RegExp(keys.map(k =>
      (isWord.test(k[0]) ? '(?<![\\p{L}\\p{N}])' : '') + esc(k) + (isWord.test(k[k.length-1]) ? '(?![\\p{L}\\p{N}])' : '')
    ).join('|'), 'gu');
    const line = s => {
      if(!CYR.test(s)) return s;
      const core = s.trim().replace(/\s+/g, ' ');
      const hit = dict[core];
      if(hit !== undefined) return s.match(/^\s*/)[0] + hit + s.match(/\s*$/)[0];
      return s.replace(re, m => dict[m] ?? m);
    };
    const cache = new Map();
    translate = s => {
      if(typeof s !== 'string' || !CYR.test(s)) return s;
      let r = cache.get(s);
      if(r === undefined){
        const whole = dict[s.trim().replace(/\s+/g, ' ')];   // a phrase that only wraps across lines
        r = whole !== undefined ? s.match(/^\s*/)[0] + whole + s.match(/\s*$/)[0] : s.split('\n').map(line).join('\n');
        if(cache.size > 5000) cache.clear();
        cache.set(s, r);
      }
      return r;
    };

    const doneText = new WeakMap(), doneAttr = new WeakMap();
    const skipped = el => !el || SKIP_TAGS.has(el.tagName) || !!el.closest('[data-i18n-skip]');
    const doText = n => {
      const v = n.data;
      if(doneText.get(n) === v || !CYR.test(v) || !n.parentElement || NO_TEXT.has(n.parentElement.tagName) || skipped(n.parentElement)) return;
      const t = translate(v); doneText.set(n, t);
      if(t !== v) n.data = t;
    };
    const doAttrs = el => {
      if(!el.getAttribute) return;
      let seen = null;
      for(const a of ATTRS){
        const v = el.getAttribute(a);
        if(!v || !CYR.test(v)) continue;
        if(seen === null){ if(skipped(el)) return; seen = doneAttr.get(el) || {}; doneAttr.set(el, seen); }
        if(seen[a] === v) continue;
        const t = translate(v); seen[a] = t;
        if(t !== v) el.setAttribute(a, t);
      }
    };
    const walk = root => {
      if(root.nodeType === 3){ doText(root); return; }
      if(root.nodeType !== 1 && root.nodeType !== 11) return;
      if(root.nodeType === 1){ if(skipped(root)) return; doAttrs(root); }
      const w = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
        acceptNode: n => n.nodeType === 1 && (SKIP_TAGS.has(n.tagName) || n.hasAttribute('data-i18n-skip')) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
      });
      for(let n = w.nextNode(); n; n = w.nextNode()) n.nodeType === 3 ? doText(n) : doAttrs(n);
    };
    new MutationObserver(muts => {
      for(const m of muts){
        if(m.type === 'characterData') doText(m.target);
        else if(m.type === 'attributes') doAttrs(m.target);
        else for(const n of m.addedNodes) walk(n);
      }
    }).observe(document.documentElement, { subtree:true, childList:true, characterData:true, attributes:true, attributeFilter:ATTRS });
    document.addEventListener('DOMContentLoaded', () => walk(document.documentElement));

    // Dialogs do not go through the DOM
    for(const name of ['alert', 'confirm']){ const orig = window[name].bind(window); window[name] = msg => orig(translate(String(msg ?? ''))); }
    const origPrompt = window.prompt.bind(window);
    window.prompt = (msg, def) => origPrompt(translate(String(msg ?? '')), def);
  }

  // ---- language picker (first start) and switcher ----
  const css = 'position:fixed;inset:0;z-index:2147483000;background:#0b0d11f0;display:flex;align-items:center;justify-content:center;font:15px/1.4 system-ui,sans-serif;color:#e6e8ee';
  function picker(){
    const wrap = document.createElement('div');
    wrap.setAttribute('data-i18n-skip', ''); wrap.style.cssText = css;
    const box = document.createElement('div');
    box.style.cssText = 'background:#171a21;border:1px solid #2a2f3a;border-radius:14px;padding:26px 28px;width:min(340px,90vw);display:flex;flex-direction:column;gap:10px;text-align:center';
    box.innerHTML = '<div style="font-size:40px">🎩</div><b style="font-size:18px">Hudini</b><div style="color:#8b91a1;font-size:13px;margin-bottom:6px">Language · Язык · Мова · Sprache</div>';
    const guess = (navigator.language || '').slice(0, 2).toLowerCase();
    const pre = LANGS.some(l => l[0] === guess) ? guess : 'en';
    for(const [code, name] of LANGS){
      const b = document.createElement('button');
      b.type = 'button'; b.textContent = name;
      b.style.cssText = 'font:inherit;padding:10px;border-radius:8px;cursor:pointer;color:#fff;border:1px solid ' + (code === pre ? '#7c5cff;background:#7c5cff' : '#2a2f3a;background:#1d212a');
      b.onclick = () => { setLang(code); wrap.remove(); };
      box.appendChild(b);
    }
    wrap.appendChild(box); document.body.appendChild(wrap);
  }
  function mountSwitch(host){
    const s = document.createElement('select');
    s.setAttribute('data-i18n-skip', ''); s.title = 'Language';
    s.style.cssText = 'font:inherit;font-size:12px;padding:3px 6px;border-radius:6px;background:#1d212a;color:#e6e8ee;border:1px solid #2a2f3a;cursor:pointer';
    for(const [code, name] of LANGS){ const o = document.createElement('option'); o.value = code; o.textContent = '🌐 ' + name; o.selected = code === lang; s.appendChild(o); }
    s.onchange = () => setLang(s.value);
    host.appendChild(s);
  }
  document.addEventListener('DOMContentLoaded', () => {
    for(const el of document.querySelectorAll('[data-i18n-switch]')) mountSwitch(el);
    if(!saved) picker();
  });

  window.HudiniI18n = { lang, langs:LANGS, setLang, t:translate, picker };
})();
